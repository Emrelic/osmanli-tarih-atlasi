-- ─── 1. PROFİLLER ──────────────────────────────────────────────────────────────
create table if not exists public.profiller (
  id            uuid primary key references auth.users(id) on delete cascade,
  kullanici_adi text unique not null
                check (kullanici_adi ~ '^[a-zA-Z0-9_.]{3,30}$'),
  gorunen_ad    text check (char_length(gorunen_ad) between 1 and 60),
  unvan         text not null default 'merakli'
                check (unvan in ('ogretmen','akademisyen','arastirmaci','ogrenci','merakli')),
  biyografi     text check (char_length(biyografi) <= 1000),
  rol           text not null default 'uye'
                check (rol in ('uye','moderator','yonetici')),
  olusturma     timestamptz not null default now()
);

-- Yetki yardımcıları (SECURITY DEFINER: RLS döngüsüne girmeden rolü okur)
create or replace function public.forum_rol() returns text
language sql stable security definer set search_path = public as $$
  select coalesce((select rol from public.profiller where id = auth.uid()), 'misafir');
$$;
create or replace function public.forum_mod_mu() returns boolean
language sql stable security definer set search_path = public as $$
  select public.forum_rol() in ('moderator','yonetici');
$$;

-- Kayıt olunca profil kendiliğinden açılır (kullanıcı adı kayıt formundan gelir)
create or replace function public.forum_yeni_kullanici() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  ad text := coalesce(nullif(new.raw_user_meta_data->>'kullanici_adi',''),
                      'uye_' || substr(replace(new.id::text,'-',''),1,8));
  un text := coalesce(new.raw_user_meta_data->>'unvan','merakli');
begin
  if un not in ('ogretmen','akademisyen','arastirmaci','ogrenci','merakli') then un := 'merakli'; end if;
  if ad !~ '^[a-zA-Z0-9_.]{3,30}$' or exists (select 1 from public.profiller where kullanici_adi = ad) then
    ad := 'uye_' || substr(replace(new.id::text,'-',''),1,8);
  end if;
  insert into public.profiller (id, kullanici_adi, gorunen_ad, unvan)
  values (new.id, ad, nullif(new.raw_user_meta_data->>'gorunen_ad',''), un)
  on conflict (id) do nothing;
  return new;
end $$;
drop trigger if exists forum_yeni_kullanici on auth.users;
create trigger forum_yeni_kullanici after insert on auth.users
  for each row execute function public.forum_yeni_kullanici();

-- Üye kendi rolünü değiştiremez (yalnız yönetici değiştirir)
create or replace function public.forum_rol_koru() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.rol is distinct from old.rol and public.forum_rol() <> 'yonetici' then
    raise exception 'rol yalnız yönetici tarafından değiştirilir';
  end if;
  if new.id <> old.id then raise exception 'id değişmez'; end if;
  return new;
end $$;
drop trigger if exists forum_rol_koru on public.profiller;
create trigger forum_rol_koru before update on public.profiller
  for each row execute function public.forum_rol_koru();

-- ─── 2. BÖLÜMLER ───────────────────────────────────────────────────────────────
create table if not exists public.bolumler (
  id        smallint generated by default as identity primary key,
  ad        text not null unique,
  aciklama  text,
  simge     text,
  sira      smallint not null default 0
);

-- ─── 3. KONULAR ────────────────────────────────────────────────────────────────
create table if not exists public.konular (
  id            bigint generated by default as identity primary key,
  bolum_id      smallint not null references public.bolumler(id),
  yazar_id      uuid not null default auth.uid() references public.profiller(id) on delete cascade,
  baslik        text not null check (char_length(baslik) between 3 and 200),
  govde         text not null check (char_length(govde) between 1 and 20000),
  olusturma     timestamptz not null default now(),
  duzenlenme    timestamptz,
  son_etkinlik  timestamptz not null default now(),
  mesaj_sayisi  integer not null default 0,
  kilitli       boolean not null default false,
  sabit         boolean not null default false,
  silindi       boolean not null default false,
  -- HARİTA BAĞLAMI (hepsi isteğe bağlı)
  baglam_tarih  date,                                   -- atlasın günü
  baglam_lng    double precision check (baglam_lng between -180 and 180),
  baglam_lat    double precision check (baglam_lat between -90 and 90),
  baglam_zoom   real check (baglam_zoom between 0 and 22),
  baglam_madde  text check (char_length(baglam_madde) <= 200),  -- kronoloji maddesi kimliği
  baglam_etiket text check (char_length(baglam_etiket) <= 200)  -- insan okunur özet
);
create index if not exists konular_bolum_idx on public.konular (bolum_id, sabit desc, son_etkinlik desc);
create index if not exists konular_tarih_idx on public.konular (baglam_tarih) where baglam_tarih is not null;

-- ─── 4. MESAJLAR (Facebook gibi iç içe cevap: ust_mesaj_id) ─────────────────────
create table if not exists public.mesajlar (
  id            bigint generated by default as identity primary key,
  konu_id       bigint not null references public.konular(id) on delete cascade,
  ust_mesaj_id  bigint references public.mesajlar(id) on delete cascade,
  yazar_id      uuid not null default auth.uid() references public.profiller(id) on delete cascade,
  govde         text not null check (char_length(govde) between 1 and 10000),
  olusturma     timestamptz not null default now(),
  duzenlenme    timestamptz,
  silindi       boolean not null default false
);
create index if not exists mesajlar_konu_idx on public.mesajlar (konu_id, olusturma);

-- Cevap verilen mesaj aynı konuda olmalı
create or replace function public.forum_mesaj_denetle() returns trigger
language plpgsql security definer set search_path = public as $$
declare k record; sayi int;
begin
  select kilitli, silindi into k from public.konular where id = new.konu_id;
  if k.kilitli and not public.forum_mod_mu() then raise exception 'konu kilitli'; end if;
  if k.silindi then raise exception 'konu silinmiş'; end if;
  if new.ust_mesaj_id is not null and not exists (
       select 1 from public.mesajlar where id = new.ust_mesaj_id and konu_id = new.konu_id) then
    raise exception 'cevap verilen mesaj bu konuda değil';
  end if;
  -- Basit sel önleyici: dakikada en çok 6 mesaj
  select count(*) into sayi from public.mesajlar
   where yazar_id = new.yazar_id and olusturma > now() - interval '1 minute';
  if sayi >= 6 then raise exception 'çok hızlı yazıyorsunuz, bir dakika bekleyin'; end if;
  return new;
end $$;
drop trigger if exists forum_mesaj_denetle on public.mesajlar;
create trigger forum_mesaj_denetle before insert on public.mesajlar
  for each row execute function public.forum_mesaj_denetle();

-- Konu için de sel önleyici: 10 dakikada en çok 3 konu
create or replace function public.forum_konu_denetle() returns trigger
language plpgsql security definer set search_path = public as $$
declare sayi int;
begin
  select count(*) into sayi from public.konular
   where yazar_id = new.yazar_id and olusturma > now() - interval '10 minutes';
  if sayi >= 3 and not public.forum_mod_mu() then
    raise exception 'çok hızlı konu açıyorsunuz, biraz bekleyin';
  end if;
  return new;
end $$;
drop trigger if exists forum_konu_denetle on public.konular;
create trigger forum_konu_denetle before insert on public.konular
  for each row execute function public.forum_konu_denetle();

-- Sayaç ve son etkinlik
create or replace function public.forum_sayac() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  update public.konular set mesaj_sayisi = mesaj_sayisi + 1, son_etkinlik = now()
   where id = new.konu_id;
  return new;
end $$;
drop trigger if exists forum_sayac on public.mesajlar;
create trigger forum_sayac after insert on public.mesajlar
  for each row execute function public.forum_sayac();

-- Üye yalnız metni düzenleyebilir; kilit/sabit/sayaç/yazar alanlarına dokunamaz
create or replace function public.forum_duzenleme_koru() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  -- Sayaç tetikleyicisinden (iç içe) gelen güncelleme serbest
  if pg_trigger_depth() > 1 then return new; end if;
  if public.forum_mod_mu() then return new; end if;
  if tg_table_name = 'konular' then
    if new.kilitli <> old.kilitli or new.sabit <> old.sabit or new.mesaj_sayisi <> old.mesaj_sayisi
       or new.bolum_id <> old.bolum_id or new.son_etkinlik <> old.son_etkinlik then
      raise exception 'bu alanı yalnız moderatör değiştirir';
    end if;
  end if;
  if new.yazar_id <> old.yazar_id or new.olusturma <> old.olusturma then
    raise exception 'yazar ve tarih değişmez';
  end if;
  if new.govde is distinct from old.govde then new.duzenlenme := now(); end if;
  return new;
end $$;
drop trigger if exists forum_duzenleme_koru on public.konular;
create trigger forum_duzenleme_koru before update on public.konular
  for each row execute function public.forum_duzenleme_koru();
drop trigger if exists forum_duzenleme_koru on public.mesajlar;
create trigger forum_duzenleme_koru before update on public.mesajlar
  for each row execute function public.forum_duzenleme_koru();

-- ─── 5. TEPKİLER (beğeni ve emoji) ─────────────────────────────────────────────
create table if not exists public.tepkiler (
  id            bigint generated by default as identity primary key,
  konu_id       bigint references public.konular(id) on delete cascade,
  mesaj_id      bigint references public.mesajlar(id) on delete cascade,
  kullanici_id  uuid not null default auth.uid() references public.profiller(id) on delete cascade,
  emoji         text not null check (emoji in ('👍','❤️','😂','😮','🤔','📚')),
  olusturma     timestamptz not null default now(),
  check ((konu_id is null) <> (mesaj_id is null))
);
create unique index if not exists tepkiler_konu_tek  on public.tepkiler (konu_id, kullanici_id, emoji) where konu_id is not null;
create unique index if not exists tepkiler_mesaj_tek on public.tepkiler (mesaj_id, kullanici_id, emoji) where mesaj_id is not null;

-- ─── 6. RLS — SATIR GÜVENLİĞİ ──────────────────────────────────────────────────
alter table public.profiller enable row level security;
alter table public.bolumler  enable row level security;
alter table public.konular   enable row level security;
alter table public.mesajlar  enable row level security;
alter table public.tepkiler  enable row level security;

-- profiller: herkes okur; herkes yalnız kendini düzenler (rolü tetikleyici korur)
drop policy if exists p_profil_oku on public.profiller;
create policy p_profil_oku on public.profiller for select using (true);
drop policy if exists p_profil_duzenle on public.profiller;
create policy p_profil_duzenle on public.profiller for update
  using (id = auth.uid() or public.forum_rol() = 'yonetici')
  with check (id = auth.uid() or public.forum_rol() = 'yonetici');

-- bolumler: herkes okur; yalnız yönetici yazar
drop policy if exists p_bolum_oku on public.bolumler;
create policy p_bolum_oku on public.bolumler for select using (true);
drop policy if exists p_bolum_yonet on public.bolumler;
create policy p_bolum_yonet on public.bolumler for all
  using (public.forum_rol() = 'yonetici') with check (public.forum_rol() = 'yonetici');

-- konular: silinmemişi herkes okur; giriş yapmış üye kendi adına açar; yazar ya da moderatör düzenler
drop policy if exists p_konu_oku on public.konular;
create policy p_konu_oku on public.konular for select
  using (not silindi or yazar_id = auth.uid() or public.forum_mod_mu());
drop policy if exists p_konu_ac on public.konular;
create policy p_konu_ac on public.konular for insert to authenticated
  with check (yazar_id = auth.uid() and not kilitli and not sabit and not silindi and mesaj_sayisi = 0);
drop policy if exists p_konu_duzenle on public.konular;
create policy p_konu_duzenle on public.konular for update to authenticated
  using (yazar_id = auth.uid() or public.forum_mod_mu())
  with check (yazar_id = auth.uid() or public.forum_mod_mu());

-- mesajlar: aynı düzen
drop policy if exists p_mesaj_oku on public.mesajlar;
create policy p_mesaj_oku on public.mesajlar for select
  using (not silindi or yazar_id = auth.uid() or public.forum_mod_mu());
drop policy if exists p_mesaj_yaz on public.mesajlar;
create policy p_mesaj_yaz on public.mesajlar for insert to authenticated
  with check (yazar_id = auth.uid() and not silindi);
drop policy if exists p_mesaj_duzenle on public.mesajlar;
create policy p_mesaj_duzenle on public.mesajlar for update to authenticated
  using (yazar_id = auth.uid() or public.forum_mod_mu())
  with check (yazar_id = auth.uid() or public.forum_mod_mu());

-- tepkiler: herkes okur; üye kendi tepkisini ekler/kaldırır
drop policy if exists p_tepki_oku on public.tepkiler;
create policy p_tepki_oku on public.tepkiler for select using (true);
drop policy if exists p_tepki_ekle on public.tepkiler;
create policy p_tepki_ekle on public.tepkiler for insert to authenticated
  with check (kullanici_id = auth.uid());
drop policy if exists p_tepki_sil on public.tepkiler;
create policy p_tepki_sil on public.tepkiler for delete to authenticated
  using (kullanici_id = auth.uid());

