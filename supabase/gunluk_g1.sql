-- ─── 1. AYRINTILI OLAY KAYDI (12 ay) ─────────────────────────────────────────────
create table if not exists public.ziyaret_olaylari (
  id      bigint generated by default as identity primary key,
  zaman   timestamptz not null default now(),
  kisi    text not null check (kisi ~ '^[A-Za-z0-9]{16,64}$'),     -- rastgele takma numara
  uye_id  uuid references auth.users(id) on delete set null,        -- yalnız giriş yapmışsa
  oturum  text check (oturum ~ '^[A-Za-z0-9]{6,32}$'),
  olay    text not null check (olay in ('acilis','madde','oynat','ucus','dil','kalma','sayfa')),
  ayrinti text check (char_length(ayrinti) <= 300),
  sayi    integer check (sayi between 0 and 86400),                  -- kalma: saniye
  cihaz   text check (cihaz in ('masaustu','telefon','tablet')),
  dil     text check (dil ~ '^[a-zA-Z]{2,8}(-[a-zA-Z0-9]{2,8})?$'),
  ulke    text check (ulke ~ '^[A-Z]{2}$')
);
create index if not exists ziyaret_zaman_idx on public.ziyaret_olaylari (zaman);
create index if not exists ziyaret_kisi_idx  on public.ziyaret_olaylari (kisi, zaman);
create index if not exists ziyaret_olay_idx  on public.ziyaret_olaylari (olay, zaman);
create index if not exists ziyaret_uye_idx   on public.ziyaret_olaylari (uye_id) where uye_id is not null;

alter table public.ziyaret_olaylari enable row level security;
revoke all on public.ziyaret_olaylari from anon, authenticated;
grant select on public.ziyaret_olaylari to authenticated;
drop policy if exists ziyaret_yonetici_oku on public.ziyaret_olaylari;
create policy ziyaret_yonetici_oku on public.ziyaret_olaylari
  for select to authenticated using (public.forum_rol() = 'yonetici');
-- (insert/update/delete politikası YOK ⇒ anon ve üyeler doğrudan yazamaz/silemez)

