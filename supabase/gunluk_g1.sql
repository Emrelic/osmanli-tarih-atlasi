-- ─── 3. KAYDET (tarayıcının TEK yazma yolu) ──────────────────────────────────────
-- p_olaylar: [{"o":"madde","a":"İstanbul'un Fethi","n":12}, ...]  (en çok 50 öğe)
-- Ülke: Supabase ön kapısının (Cloudflare) 'cf-ipcountry' başlığı; yoksa tarayıcının
-- saat-dilimi tahmini (p_ulke_ipucu). Ham IP hiçbir yerde okunmaz, yazılmaz.
create or replace function public.ziyaret_kaydet(
  p_kisi text, p_oturum text, p_olaylar jsonb,
  p_cihaz text default null, p_dil text default null, p_ulke_ipucu text default null
) returns void
language plpgsql security definer set search_path = public as $$
declare
  e      jsonb;
  ulke   text;
  cihaz  text := nullif(p_cihaz, '');
  dil    text := nullif(p_dil, '');
  oturum text := nullif(p_oturum, '');
  uid    uuid := auth.uid();
  sayi   integer;
begin
  if p_kisi is null or p_kisi !~ '^[A-Za-z0-9]{16,64}$' then return; end if;
  if p_olaylar is null or jsonb_typeof(p_olaylar) <> 'array' then return; end if;
  -- taşma koruması (ücretsiz katman 500 MB): yaklaşık satır sayısı sınırı aşıldıysa yeni kayıt almaz
  if coalesce((select reltuples::bigint from pg_class
                where oid = 'public.ziyaret_olaylari'::regclass), 0) > 3000000 then return; end if;

  if cihaz is not null and cihaz not in ('masaustu','telefon','tablet') then cihaz := null; end if;
  if dil is not null and dil !~ '^[a-zA-Z]{2,8}(-[a-zA-Z0-9]{2,8})?$' then dil := null; end if;
  if oturum is not null and oturum !~ '^[A-Za-z0-9]{6,32}$' then oturum := null; end if;

  begin
    ulke := upper(nullif((current_setting('request.headers', true)::json) ->> 'cf-ipcountry', ''));
  exception when others then ulke := null;
  end;
  if ulke is null or ulke !~ '^[A-Z]{2}$' or ulke in ('XX','T1') then
    ulke := upper(nullif(p_ulke_ipucu, ''));
    if ulke is not null and ulke !~ '^[A-Z]{2}$' then ulke := null; end if;
  end if;

  for e in select value from jsonb_array_elements(p_olaylar) limit 50 loop
    if jsonb_typeof(e) <> 'object' then continue; end if;
    if (e ->> 'o') not in ('acilis','madde','oynat','ucus','dil','kalma','sayfa') then continue; end if;
    sayi := null;
    if (e ->> 'n') ~ '^[0-9]{1,6}$' then sayi := least((e ->> 'n')::integer, 86400); end if;
    insert into public.ziyaret_olaylari (kisi, uye_id, oturum, olay, ayrinti, sayi, cihaz, dil, ulke)
    values (p_kisi, uid, oturum, e ->> 'o', left(nullif(e ->> 'a', ''), 300), sayi, cihaz, dil, ulke);
  end loop;
end $$;
revoke all on function public.ziyaret_kaydet(text,text,jsonb,text,text,text) from public;
grant execute on function public.ziyaret_kaydet(text,text,jsonb,text,text,text) to anon, authenticated;

-- ─── 4. SİL ("verilerimi sil": kendi numarasının ve giriş yapmışsa hesabının kayıtları) ──
create or replace function public.ziyaret_sil(p_kisi text default null) returns integer
language plpgsql security definer set search_path = public as $$
declare n integer := 0; uid uuid := auth.uid();
begin
  if p_kisi is not null and p_kisi ~ '^[A-Za-z0-9]{16,64}$' then
    delete from public.ziyaret_olaylari where kisi = p_kisi;
    get diagnostics n = row_count;
  end if;
  if uid is not null then
    delete from public.ziyaret_olaylari where uye_id = uid;
  end if;
  return n;
end $$;
revoke all on function public.ziyaret_sil(text) from public;
grant execute on function public.ziyaret_sil(text) to anon, authenticated;

-- ─── 5. 12 AY SAKLAMA ────────────────────────────────────────────────────────────
-- 12 aydan eski ayrıntı günlük özete katılır, sonra silinir. Yalnız zamanlayıcı (postgres)
-- çağırır: anon/authenticated çağıramaz.
create or replace function public.ziyaret_temizle() returns integer
language plpgsql security definer set search_path = public as $$
declare n integer;
begin
  insert into public.ziyaret_gunluk (gun, olay, ulke, cihaz, dil, adet, kisi_sayisi)
  select (zaman at time zone 'UTC')::date, olay, coalesce(ulke,'??'), coalesce(cihaz,'??'),
         coalesce(lower(dil),'??'), count(*), count(distinct kisi)
    from public.ziyaret_olaylari
   where zaman < now() - interval '12 months'
   group by 1,2,3,4,5
  on conflict (gun, olay, ulke, cihaz, dil) do update
    set adet = public.ziyaret_gunluk.adet + excluded.adet,
        kisi_sayisi = greatest(public.ziyaret_gunluk.kisi_sayisi, excluded.kisi_sayisi);
  delete from public.ziyaret_olaylari where zaman < now() - interval '12 months';
  get diagnostics n = row_count;
  return n;
end $$;
revoke all on function public.ziyaret_temizle() from public, anon, authenticated;

-- Her gece 03:15 UTC (pg_cron kapalıysa uyarı verir; Dashboard → Database → Extensions → pg_cron aç, sonra bu bloğu yeniden koş)
do $$
begin
  create extension if not exists pg_cron;
  perform cron.unschedule(jobid) from cron.job where jobname = 'ziyaret_temizle';
  perform cron.schedule('ziyaret_temizle', '15 3 * * *', 'select public.ziyaret_temizle()');
exception when others then
  raise notice 'pg_cron kurulamadı (%): 12 ay temizliğini elle ya da sonra zamanlayın', sqlerrm;
end $$;

-- ─── 6. PANEL ÖZETİ (yalnız yönetici) ────────────────────────────────────────────
create or replace function public.ziyaret_ozet(p_gun integer default 30) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  bas timestamptz := now() - make_interval(days => least(greatest(coalesce(p_gun,30),1),365));
  s   jsonb;
begin
  if public.forum_rol() <> 'yonetici' then
    raise exception 'yalnız yönetici';
  end if;
  select jsonb_build_object(
    'bas', bas,
    'toplam_olay',  (select count(*) from public.ziyaret_olaylari where zaman >= bas),
    'ziyaretci',    (select count(distinct kisi) from public.ziyaret_olaylari where zaman >= bas),
    'uye_ziyaretci',(select count(distinct uye_id) from public.ziyaret_olaylari where zaman >= bas and uye_id is not null),
    'oturum',       (select count(distinct oturum) from public.ziyaret_olaylari where zaman >= bas),
    'ort_kalma_sn', (select round(avg(sayi)) from public.ziyaret_olaylari where zaman >= bas and olay = 'kalma'),
    'gunluk', coalesce((select jsonb_agg(g order by g->>'gun') from (
        select jsonb_build_object('gun', (zaman at time zone 'UTC')::date,
                                  'ziyaretci', count(distinct kisi),
                                  'uye', count(distinct uye_id),
                                  'acilis', count(*) filter (where olay = 'acilis')) g
          from public.ziyaret_olaylari where zaman >= bas
         group by (zaman at time zone 'UTC')::date) x), '[]'::jsonb),
    'ulke', coalesce((select jsonb_agg(g order by (g->>'kisi')::int desc) from (
        select jsonb_build_object('ad', coalesce(ulke,'??'), 'kisi', count(distinct kisi)) g
          from public.ziyaret_olaylari where zaman >= bas group by ulke
         order by count(distinct kisi) desc limit 20) x), '[]'::jsonb),
    'cihaz', coalesce((select jsonb_agg(g order by (g->>'kisi')::int desc) from (
        select jsonb_build_object('ad', coalesce(cihaz,'??'), 'kisi', count(distinct kisi)) g
          from public.ziyaret_olaylari where zaman >= bas group by cihaz) x), '[]'::jsonb),
    'dil', coalesce((select jsonb_agg(g order by (g->>'kisi')::int desc) from (
        select jsonb_build_object('ad', coalesce(lower(dil),'??'), 'kisi', count(distinct kisi)) g
          from public.ziyaret_olaylari where zaman >= bas group by lower(dil)
         order by count(distinct kisi) desc limit 25) x), '[]'::jsonb),
    'madde', coalesce((select jsonb_agg(g order by (g->>'adet')::int desc) from (
        select jsonb_build_object('ad', ayrinti, 'adet', count(*), 'kisi', count(distinct kisi)) g
          from public.ziyaret_olaylari where zaman >= bas and olay = 'madde' and ayrinti is not null
         group by ayrinti order by count(*) desc limit 25) x), '[]'::jsonb),
    'ucus', coalesce((select jsonb_agg(g order by (g->>'adet')::int desc) from (
        select jsonb_build_object('ad', coalesce(ayrinti,'?'), 'adet', count(*)) g
          from public.ziyaret_olaylari where zaman >= bas and olay = 'ucus'
         group by ayrinti) x), '[]'::jsonb),
    'oynat', (select count(*) from public.ziyaret_olaylari where zaman >= bas and olay = 'oynat'),
    'uyeler', coalesce((select jsonb_agg(g order by (g->>'olay')::int desc) from (
        select jsonb_build_object('kullanici', p.kullanici_adi, 'olay', count(*),
                                  'son', max(o.zaman),
                                  'kalma_sn', coalesce(sum(o.sayi) filter (where o.olay = 'kalma'), 0)) g
          from public.ziyaret_olaylari o
          join public.profiller p on p.id = o.uye_id
         where o.zaman >= bas
         group by p.kullanici_adi order by count(*) desc limit 50) x), '[]'::jsonb),
    'arsiv_gun', (select count(*) from public.ziyaret_gunluk)
  ) into s;
  return s;
end $$;
revoke all on function public.ziyaret_ozet(integer) from public, anon;
grant execute on function public.ziyaret_ozet(integer) to authenticated;
