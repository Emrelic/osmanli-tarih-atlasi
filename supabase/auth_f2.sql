-- ─── 1. Rıza (KVKK/GDPR) kaydı ────────────────────────────────────────────────────
alter table public.profiller add column if not exists riza_zamani timestamptz;
alter table public.profiller add column if not exists riza_surumu text;

-- Kayıt tetikleyicisi: forum_f1.sql'dekinin aynısı + rıza kaydı. Kullanıcı adı kuralı ve
-- yedek ad (uye_xxxxxxxx) aynı kalır.
create or replace function public.forum_yeni_kullanici() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  ad text := coalesce(nullif(new.raw_user_meta_data->>'kullanici_adi',''),
                      'uye_' || substr(replace(new.id::text,'-',''),1,8));
  un text := coalesce(new.raw_user_meta_data->>'unvan','merakli');
  riza boolean := coalesce((new.raw_user_meta_data->>'kvkk_riza')::boolean, false);
begin
  if un not in ('ogretmen','akademisyen','arastirmaci','ogrenci','merakli') then un := 'merakli'; end if;
  if ad !~ '^[a-zA-Z0-9_.]{3,30}$' or exists (select 1 from public.profiller where lower(kullanici_adi) = lower(ad)) then
    ad := 'uye_' || substr(replace(new.id::text,'-',''),1,8);
  end if;
  insert into public.profiller (id, kullanici_adi, gorunen_ad, unvan, riza_zamani, riza_surumu)
  values (new.id, ad, nullif(new.raw_user_meta_data->>'gorunen_ad',''), un,
          case when riza then now() end,
          case when riza then left(new.raw_user_meta_data->>'kvkk_surum', 20) end)
  on conflict (id) do nothing;
  return new;
end $$;

-- Kullanıcı adı büyük/küçük harfe duyarsız benzersiz olsun (Ali ≠ ali karışıklığı olmasın)
create unique index if not exists profiller_kullanici_adi_kucuk_idx on public.profiller (lower(kullanici_adi));

-- ─── 2. Kullanıcı adı müsait mi? (yalnız doğru/yanlış döner; liste sızdırmaz) ───────
create or replace function public.kullanici_adi_musait(ad text) returns boolean
language sql stable security definer set search_path = public as $$
  select ad ~ '^[a-zA-Z0-9_.]{3,30}$'
     and not exists (select 1 from public.profiller where lower(kullanici_adi) = lower(ad));
$$;
revoke all on function public.kullanici_adi_musait(text) from public;
grant execute on function public.kullanici_adi_musait(text) to anon, authenticated;

-- ─── 3. Hesabı sil (kendi hesabı; forum içeriği on delete cascade ile gider) ────────
create or replace function public.hesabi_sil() returns void
language plpgsql security definer set search_path = public, auth as $$
begin
  if auth.uid() is null then raise exception 'oturum yok'; end if;
  delete from auth.users where id = auth.uid();
end $$;
revoke all on function public.hesabi_sil() from public, anon;
grant execute on function public.hesabi_sil() to authenticated;

-- ─── 4. Verilerimi indir (erişim/taşınabilirlik hakkı) — RLS'e tabidir (invoker) ─────
create or replace function public.verilerimi_indir() returns jsonb
language sql stable security invoker set search_path = public as $$
  select jsonb_build_object(
    'profil',  (select to_jsonb(p) from public.profiller p where p.id = auth.uid()),
    'konular', coalesce((select jsonb_agg(to_jsonb(k)) from public.konular k where k.yazar_id = auth.uid()), '[]'::jsonb),
    'mesajlar', coalesce((select jsonb_agg(to_jsonb(m)) from public.mesajlar m where m.yazar_id = auth.uid()), '[]'::jsonb),
    'tepkiler', coalesce((select jsonb_agg(to_jsonb(t)) from public.tepkiler t where t.kullanici_id = auth.uid()), '[]'::jsonb)
  );
$$;
revoke all on function public.verilerimi_indir() from public, anon;
grant execute on function public.verilerimi_indir() to authenticated;

-- ─── 5. Hız sınırı kaydı (yalnız Edge Function "kullanici-girisi" yazar/okur) ──────
create table if not exists public.giris_deneme (
  id      bigint generated by default as identity primary key,
  anahtar text not null,                      -- "ip:<hash>" ya da "kim:<hash>" (ham değer tutulmaz)
  zaman   timestamptz not null default now()
);
create index if not exists giris_deneme_idx on public.giris_deneme (anahtar, zaman desc);
alter table public.giris_deneme enable row level security;   -- politika YOK ⇒ anon/authenticated hiçbir şey göremez
-- ─── 6. Doğrulanmamış hesapları temizle (aydınlatma metni: "en geç 30 gün") ─────────
create or replace function public.dogrulanmamis_temizle() returns integer
language plpgsql security definer set search_path = public, auth as $$
declare n integer;
begin
  delete from auth.users where email_confirmed_at is null and last_sign_in_at is null
     and created_at < now() - interval '30 days';
  get diagnostics n = row_count; return n;
end $$;
revoke all on function public.dogrulanmamis_temizle() from public, anon, authenticated;
